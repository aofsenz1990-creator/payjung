/**
 * ออกจากระบบอัตโนมัติเมื่อลูกค้าทิ้งหน้าเว็บไว้เฉย ๆ
 *
 * ทำไมต้องมี: บัญชีลูกค้ามี "ยอดเงิน" ที่กดสั่งซื้อได้ทันที ถ้าลูกค้าไปล็อกอินที่ร้านเน็ต
 * หรือมือถือของเพื่อนแล้วลืมกดออก คนถัดไปที่หยิบเครื่องขึ้นมาจะสั่งเติมเกมกินยอดเงินได้เลย
 *
 * ไฟล์นี้ตั้งใจให้มีแต่ค่าคงที่ล้วน ๆ ไม่นำเข้าอะไรเลย เพราะถูกใช้ทั้งใน
 * middleware (ทำงานบน Edge นำเข้า next/headers ไม่ได้) และในคอมโพเนนต์ฝั่งเบราว์เซอร์
 */

/** ค่าเริ่มต้น 30 นาที — ยาวพอให้ลูกค้าเลือกแพ็กเกจไม่รีบ แต่สั้นพอที่เครื่องจะไม่ค้างทิ้งไว้ข้ามวัน */
const DEFAULT_MINUTES = 30

function readMinutes(): number {
  // ต้องเขียน process.env.NEXT_PUBLIC_... ตรง ๆ แบบนี้ ห้ามอ่านผ่านตัวแปร
  // ไม่งั้น Next จะแทนค่าลงในไฟล์ฝั่งเบราว์เซอร์ให้ไม่ได้ แล้วฝั่งหน้าจอจะได้ค่าเริ่มต้นเสมอ
  const raw = Number(process.env.NEXT_PUBLIC_SHOP_IDLE_MINUTES)
  if (!Number.isFinite(raw) || raw < 1) return DEFAULT_MINUTES
  // กันตั้งค่าพลาดเป็นเลขมหาศาลจนเท่ากับไม่มีระบบนี้
  return Math.min(Math.round(raw), 12 * 60)
}

/** ปล่อยให้นิ่งได้กี่นาทีก่อนถูกพาออกจากระบบ (ตั้งค่าใหม่ได้ที่ NEXT_PUBLIC_SHOP_IDLE_MINUTES) */
export const SHOP_IDLE_MINUTES = readMinutes()

export const SHOP_IDLE_MS = SHOP_IDLE_MINUTES * 60_000

